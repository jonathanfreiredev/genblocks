"""Generate the stock pictures the seed only describes.

The seed writes six image rows with a prompt, a size and a score, and paths such as
``genblocks/images/stone-harbour`` that no cloud has a file behind. This asks the
image provider for each one, stores the bytes under their own hash and points the
row at the real public id.

Same idea as ``app.seed.screenshots``: the seed describes, this pays once for the
bytes. It skips a row whose path is already an asset id, so running it twice does
not pay twice.
"""

import asyncio

import structlog
from sqlalchemy import select

from app.categories.models import Category  # noqa: F401  (register the tables the keys point at)
from app.db.session import async_session_maker
from app.harness import cloudinary, images
from app.images.models import Image
from app.users.models import User  # noqa: F401  (pictures point at it)

logger = structlog.get_logger("app.seed.stock")


def _is_asset(path: str) -> bool:
    """Whether the path is already the hash of generated bytes.

    The seed's placeholder is a readable name; a generated picture is stored under
    the first characters of its own sha256. Sixteen hex characters is specific
    enough that no placeholder looks like it by accident.
    """
    name = path.rsplit("/", 1)[-1]

    return len(name) == cloudinary.IMAGE_ID_LENGTH and all(
        character in "0123456789abcdef" for character in name
    )


async def main() -> None:
    """Generate and store whatever the image rows are still only describing."""
    generated = 0
    skipped = 0

    async with async_session_maker() as session:
        rows = list(
            await session.scalars(
                select(Image).where(Image.deleted_at.is_(None)).order_by(Image.path)
            )
        )

        for row in rows:
            if _is_asset(row.path):
                logger.info("already generated", path=row.path)
                skipped += 1
                continue

            picture = await images.generate(prompt=row.prompt, width=row.width, height=row.height)
            row.path = picture.path
            await session.commit()
            generated += 1

            logger.info(
                "generated",
                prompt=row.prompt[:60],
                width=row.width,
                height=row.height,
                path=picture.path,
            )

    logger.info("stock done", generated=generated, skipped=skipped)


if __name__ == "__main__":
    asyncio.run(main())
