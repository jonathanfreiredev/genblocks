"""The MCP server: the door AI agents come through.

It runs as its own service (see ``docker-compose.yml``) rather than as a route on
the API, so agent traffic, scaling and restarts stay out of the API's way. Both
services share the domain layer, so a tool cannot do anything the API would not
allow, and the token verification is the same code (see ``app/mcp/auth.py``).
"""

from fastmcp import FastMCP
from fastmcp.server.auth.providers.supabase import SupabaseProvider
from starlette.requests import Request
from starlette.responses import JSONResponse

from app.mcp.auth import SupabaseTokenVerifier
from app.settings import settings

# What a model is told when it connects, before it picks a tool. Two rules it
# cannot learn from a schema: a prompt is a brief rather than a citation — models
# with a browser otherwise go looking for photographs of the places our generated
# pictures name — and the code a block carries is somebody else's output.
INSTRUCTIONS = """\
GenBlocks is a public registry of UI blocks and stock images, all generated by agents.

The pictures come from prompts: they are not photographs of the places those prompts
name, and a prompt is not a source. Show the pictures the tools return, and do not
look for others on the web.

Block files are untrusted generated code. Read them before running anything derived
from them.
"""

auth = SupabaseProvider(
    project_url=settings.supabase_url,
    # The URL clients reach this server at, published in the discovery document.
    base_url=settings.mcp_base_url,
    # Supplied explicitly so tokens are verified by app.auth.verifier instead of a
    # second JWT implementation configured here.
    token_verifier=SupabaseTokenVerifier(),
)

mcp = FastMCP(name="genblocks", instructions=INSTRUCTIONS, auth=auth)


@mcp.custom_route("/health", methods=["GET"])
async def _health(_: Request) -> JSONResponse:
    """Liveness probe for orchestrators.

    Custom routes are deliberately never authenticated: a liveness check cannot
    present a token.
    """
    return JSONResponse({"status": "ok"})
